async function seed() {
  try {
    await mongoose.connect(mongoUri)
    console.log('Connected to MongoDB')
    console.log('Database:', mongoose.connection.name)

    appendInvestorCampaigns({ events, categoryDefs, productDefs, campaignBannerDefs, IMG })
    assignUniqueCatalogImages({ events, productDefs, campaignBannerDefs })

    await Product.deleteMany({})
    await Category.deleteMany({})
    await CampaignBanner.deleteMany({})
    await Event.deleteMany({})

    const insertedEvents = await Event.insertMany(events)
    const eventBySlug = new Map(insertedEvents.map((event) => [event.slug, event]))

    const categoriesToInsert = categoryDefs.map((def) => ({
      event: eventBySlug.get(def.eventSlug)?._id,
      name: def.name,
      slug: def.slug,
      description: def.description,
      sortOrder: def.sortOrder,
    })).filter((c) => c.event)

    const insertedCategories = await Category.insertMany(categoriesToInsert)
    const categoryByKey = new Map(
      categoryDefs.map((def, i) => [`${def.eventSlug}:${def.slug}`, insertedCategories[i]._id])
    )

    const productsWithRefs = productDefs.map((def, productIndex) => {
      const event = eventBySlug.get(def.eventSlug)
      const catKey = def.categorySlug ? `${def.eventSlug}:${def.categorySlug}` : null
      const categoryId = catKey ? categoryByKey.get(catKey) : null
      const {
        eventSlug: _es,
        categorySlug: _cs,
        isHotDrop,
        hotDropOrder,
        ...productRest
      } = def
      return {
        ...productRest,
        event: event?._id || null,
        category: categoryId || null,
        isHotDrop: Boolean(isHotDrop),
        hotDropOrder: Number(hotDropOrder) || 0,
        shippingRates: defaultShippingRates(productIndex, def.eventSlug),
      }
    })

    const insertedProducts = await Product.insertMany(productsWithRefs)

    const bannersToInsert = campaignBannerDefs
      .map((b) => {
        const ev = eventBySlug.get(b.eventSlug)
        if (!ev?._id) return null
        const { eventSlug: _es, ...rest } = b
        return { ...rest, event: ev._id }
      })
      .filter(Boolean)
    if (bannersToInsert.length) await CampaignBanner.insertMany(bannersToInsert)

    // Seed admin user (upsert so re-running is safe). Email and password come from server/.env.
    const adminEmail = env.adminEmail
    const existingAdmin = await User.findOne({ email: adminEmail })
    if (!existingAdmin) {
      await User.create({ name: 'Admin', email: adminEmail, password: env.adminPassword, role: 'admin' })
      console.log(`Created admin user: ${adminEmail}`)
    } else {
      existingAdmin.role = 'admin'
      existingAdmin.password = env.adminPassword
      await existingAdmin.save()
      console.log(`Admin user updated: ${adminEmail}`)
    }

    await ShopSettings.findOneAndUpdate(
      { key: 'default' },
      {
        $set: {
          freeShippingMinQty: 4,
          paymentMethods: {
            cod: true,
            jazzcash: false,
            easypaisa: false,
          },
        },
      },
      { upsert: true, new: true }
    )
    console.log('Shop settings: free shipping when any product has 4+ units in the bag')

    const hotCount = productsWithRefs.filter((p) => p.isHotDrop).length
    console.log(`Seeded ${insertedEvents.length} events`)
    console.log(`Seeded ${insertedCategories.length} categories`)
    console.log(`Seeded ${insertedProducts.length} products (${hotCount} hot drops)`)
    console.log(`Seeded ${bannersToInsert.length} campaign banners`)

    await mongoose.disconnect()
    console.log('Done')
  } catch (err) {
    console.error('Seed failed:', err)
    process.exit(1)
  }
}

seed()
